async def run_ast_grep(module_path: Path) -> ToolResult:
    """Run ast-grep on module."""
    # Run ast-grep with rules from .ast-grep directory
    ast_grep_dir = Path.cwd() / ".ast-grep"
    if not ast_grep_dir.exists():
        return ToolResult(tool="ast-grep", success=True, errors=[])

    cmd = ["ast-grep", "scan", "--json", str(module_path)]
    stdout, stderr, exit_code = await run_command(cmd)

    errors = parse_ast_grep_output(stdout)

    return ToolResult(
        tool="ast-grep",
        success=len(errors) == 0,
        errors=errors,
        stdout=stdout,
        stderr=stderr,
        exit_code=exit_code,
    )


async def run_semgrep(module_path: Path) -> ToolResult:
    """Run semgrep on module."""
    cmd = ["uv", "run", "semgrep", "scan", "--config=auto", "--json", str(module_path)]

    # Create subprocess with environment variables for proxy
    process = await asyncio.create_subprocess_exec(
        *cmd,
        stdout=asyncio.subprocess.PIPE,
        stderr=asyncio.subprocess.PIPE,
        env={
            **os.environ,
            "CUSTOM_CERT_BUNDLE_PATH": "/Users/Shared/ca_certs/bundle.pem",
            "HTTP_PROXY": "http://localhost:3128",
            "HTTPS_PROXY": "http://localhost:3128",
        },
    )
    stdout_bytes, stderr_bytes = await process.communicate()
    stdout = stdout_bytes.decode("utf-8", errors="replace")
    stderr = stderr_bytes.decode("utf-8", errors="replace")
    exit_code = process.returncode or 0

    errors = parse_semgrep_output(stdout)

    # Semgrep exit codes: 0 = no findings, 1 = findings found, 2+ = error
    # Success means semgrep ran (exit 0 or 1), not whether it found issues
    return ToolResult(
        tool="semgrep",
        success=exit_code in (0, 1),
        errors=errors,
        stdout=stdout,
        stderr=stderr,
        exit_code=exit_code,
    )


