#!/usr/bin/env python3
"""
Run quality checks in parallel and output structured JSON.

Runs pyright, pyrefly, mypy, ruff, ast-grep, semgrep, and importlinter concurrently
and aggregates results by file.
"""

import argparse
import asyncio
import json
import os
import re
import subprocess
import sys
import tomllib
from collections import defaultdict
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any


@dataclass
class Error:
    """A single error from a quality tool."""

    file: str
    line: int | None
    code: str
    message: str
    tool: str
    severity: str = "error"


@dataclass
class ToolResult:
    """Result from running a single tool."""

    tool: str
    success: bool
    errors: list[Error] = field(default_factory=list)
    stdout: str = ""
    stderr: str = ""
    exit_code: int = 0


@dataclass
class QualityReport:
    """Aggregated quality check report."""

    verdict: str  # "PASS" or "FAIL"
    total_errors: int
    errors_by_file: dict[str, list[Error]] = field(default_factory=dict)
    errors_by_tool: dict[str, list[Error]] = field(default_factory=dict)
    tool_results: list[ToolResult] = field(default_factory=list)


def extract_excludes_from_pyproject() -> list[str]:
    """Extract exclude patterns from pyproject.toml as union of all tool excludes."""
    pyproject_path = Path.cwd() / "pyproject.toml"
    if not pyproject_path.exists():
        return []

    with open(pyproject_path, "rb") as f:
        config = tomllib.load(f)

    all_excludes: set[str] = set()

    # Get ruff extend-exclude patterns
    ruff_excludes = config.get("tool", {}).get("ruff", {}).get("extend-exclude", [])
    if ruff_excludes:
        all_excludes.update(ruff_excludes)
        print(f"Found {len(ruff_excludes)} ruff excludes", file=sys.stderr)

    # Get pyright exclude patterns
    pyright_excludes = config.get("tool", {}).get("pyright", {}).get("exclude", [])
    if pyright_excludes:
        all_excludes.update(pyright_excludes)
        print(f"Found {len(pyright_excludes)} pyright excludes", file=sys.stderr)

    # If no exclusions found, return empty list
    if not all_excludes:
        return []

    print(f"Union: {len(all_excludes)} total excludes", file=sys.stderr)
    return sorted(all_excludes)  # Return sorted list for deterministic output


def generate_ast_grep_config(excludes: list[str]) -> None:
    """Generate .ast-grep/sgconfig.yml from exclude patterns."""
    ast_grep_dir = Path.cwd() / ".ast-grep"
    if not ast_grep_dir.exists():
        return

    sgconfig_path = ast_grep_dir / "sgconfig.yml"

    # Build the config content
    config_lines = [
        "ruleDirs:",
        "  - rules",
        "languageGlobs:",
        "  python:",
        '    - "**/*.py"',
        "    # Exclusions from pyproject.toml (auto-generated)",
    ]

    # Add negation patterns for each exclude
    for exclude in excludes:
        # Convert to negation pattern
        if not exclude.startswith("!"):
            # If pattern doesn't already end with /** and doesn't have a file extension,
            # add /** to match directory contents
            if not exclude.endswith("/**") and "**" not in exclude and "*." not in exclude:
                # This looks like a directory pattern
                if exclude.endswith("/"):
                    pattern = f"{exclude}**"
                else:
                    pattern = f"{exclude}/**"
            else:
                pattern = exclude
            config_lines.append(f'    - "!{pattern}"')

    config_lines.append("")  # Trailing newline

    # Write the config file
    sgconfig_path.write_text("\n".join(config_lines))
    print(f"Generated {sgconfig_path} with {len(excludes)} exclusions", file=sys.stderr)


def generate_semgrep_ignore(excludes: list[str]) -> Path:
    """Generate temporary .semgrepignore file from exclude patterns."""
    semgrepignore_path = Path.cwd() / ".semgrepignore"

    # Build the ignore file content
    ignore_lines = [
        "# Auto-generated from pyproject.toml - DO NOT EDIT",
        "# This file is regenerated by run-quality-checks.py",
        "",
    ]

    # Add each exclude pattern
    for exclude in excludes:
        # semgrep uses gitignore-style patterns
        ignore_lines.append(exclude)

    ignore_lines.append("")  # Trailing newline

    # Write the ignore file
    semgrepignore_path.write_text("\n".join(ignore_lines))
    print(f"Generated {semgrepignore_path} with {len(excludes)} exclusions", file=sys.stderr)

    return semgrepignore_path


async def run_command(cmd: list[str], cwd: Path | None = None) -> tuple[str, str, int]:
    """Run command asynchronously and return (stdout, stderr, exit_code)."""
    process = await asyncio.create_subprocess_exec(
        *cmd,
        stdout=asyncio.subprocess.PIPE,
        stderr=asyncio.subprocess.PIPE,
        cwd=cwd,
    )
    stdout_bytes, stderr_bytes = await process.communicate()
    stdout = stdout_bytes.decode("utf-8", errors="replace")
    stderr = stderr_bytes.decode("utf-8", errors="replace")
    return stdout, stderr, process.returncode or 0


def parse_pyright_output(output: str) -> list[Error]:
    """Parse pyright JSON output into Error objects."""
    errors = []
    try:
        data = json.loads(output)
        # Pyright JSON structure: {"generalDiagnostics": [...], ...}
        for diagnostic in data.get("generalDiagnostics", []):
            errors.append(
                Error(
                    file=diagnostic.get("file", ""),
                    line=diagnostic.get("range", {}).get("start", {}).get("line", 0) + 1,  # Pyright uses 0-indexed lines
                    code=diagnostic.get("rule", "unknown"),
                    message=diagnostic.get("message", ""),
                    tool="pyright",
                    severity=diagnostic.get("severity", "error"),
                )
            )
    except (json.JSONDecodeError, KeyError, TypeError):
        # Fallback to text parsing if JSON parsing fails
        pattern = r"^(.+?):(\d+):(\d+)\s*-\s*(error|warning):\s*(.+?)(?:\s*\[([^\]]+)\])?$"
        for line in output.splitlines():
            match = re.match(pattern, line.strip())
            if match:
                file_path, line_no, _, severity, message, code = match.groups()
                errors.append(
                    Error(
                        file=file_path,
                        line=int(line_no),
                        code=code or "unknown",
                        message=message.strip(),
                        tool="pyright",
                        severity=severity,
                    )
                )
    return errors


