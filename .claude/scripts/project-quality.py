async def run_all_checks(module_path: Path) -> list[ToolResult]:
    """Run all quality checks in parallel (excluding import-linter, pyright, and pyrefly which run project-wide)."""
    results = await asyncio.gather(
        run_ruff(module_path),
        run_ast_grep(module_path),
        run_semgrep(module_path),
        return_exceptions=True,
    )

    # Filter out exceptions and convert to ToolResult
    tool_results = []
    for result in results:
        if isinstance(result, Exception):
            print(f"Tool execution failed: {result}", file=sys.stderr)
            continue
        if isinstance(result, ToolResult):
            tool_results.append(result)

    return tool_results


def aggregate_errors(tool_results: list[ToolResult]) -> QualityReport:
    """Aggregate errors from all tools by file and by tool."""
    errors_by_file: dict[str, list[Error]] = defaultdict(list)
    errors_by_tool: dict[str, list[Error]] = defaultdict(list)
    total_errors = 0

    for tool_result in tool_results:
        for error in tool_result.errors:
            total_errors += 1
            if error.file:
                errors_by_file[error.file].append(error)
            errors_by_tool[error.tool].append(error)

    verdict = "PASS" if total_errors == 0 else "FAIL"

    return QualityReport(
        verdict=verdict,
        total_errors=total_errors,
        errors_by_file=dict(errors_by_file),
        errors_by_tool=dict(errors_by_tool),
        tool_results=tool_results,
    )


def report_to_dict(report: QualityReport) -> dict[str, Any]:
    """Convert QualityReport to JSON-serializable dict."""
    return {
        "verdict": report.verdict,
        "total_errors": report.total_errors,
        "errors_by_file": {
            file: [
                {
                    "line": err.line,
                    "code": err.code,
                    "message": err.message,
                    "tool": err.tool,
                    "severity": err.severity,
                }
                for err in errors
            ]
            for file, errors in sorted(report.errors_by_file.items())
        },
        "errors_by_tool": {
            tool: [
                {
                    "file": err.file,
                    "line": err.line,
                    "code": err.code,
                    "message": err.message,
                    "severity": err.severity,
                }
                for err in errors
            ]
            for tool, errors in report.errors_by_tool.items()
        },
        "tool_results": [
            {
                "tool": result.tool,
                "success": result.success,
                "error_count": len(result.errors),
                "exit_code": result.exit_code,
            }
            for result in report.tool_results
        ],
    }


def report_to_dict_blind(report: QualityReport) -> dict[str, Any]:
    """Convert QualityReport to blind JSON format (aggregated by tool and error type, no file paths)."""
    # Aggregate error types by tool
    errors_by_tool_and_type: dict[str, dict[str, int]] = defaultdict(lambda: defaultdict(int))

    for tool_result in report.tool_results:
        for error in tool_result.errors:
            # Use error code as the type identifier
            error_type = error.code if error.code else "unknown"
            errors_by_tool_and_type[error.tool][error_type] += 1

    return {
        "verdict": report.verdict,
        "total_errors": report.total_errors,
        "errors_by_tool": {
            tool: dict(error_types)
            for tool, error_types in sorted(errors_by_tool_and_type.items())
        },
    }


def find_module_root(path: Path) -> Path:
    """Find the top-level module root for a given file or directory.

    Walks up the directory tree to find a directory containing pyproject.toml,
    then returns the src/ subdirectory if it exists, otherwise the directory itself.
    """
    current = path if path.is_dir() else path.parent

    # Walk up until we find pyproject.toml
    while current != current.parent:
        if (current / "pyproject.toml").exists():
            # Check if src/ subdirectory exists
            src_dir = current / "src"
            if src_dir.exists() and src_dir.is_dir():
                return src_dir
            return current
        current = current.parent

    # If no pyproject.toml found, return the original path
    return path if path.is_dir() else path.parent


def find_unique_module_roots(paths: list[Path]) -> set[Path]:
    """Find unique top-level module roots for all provided paths."""
    roots = set()
    for path in paths:
        if not path.exists():
            print(f"Warning: Path does not exist: {path}", file=sys.stderr)
            continue
        root = find_module_root(path)
        roots.add(root.resolve())
    return roots


async def run_checks_for_module(module_path: Path) -> tuple[Path, list[ToolResult]]:
    """Run all quality checks for a single module."""
    print(f"Running quality checks on: {module_path}", file=sys.stderr)
    tool_results = await run_all_checks(module_path)
    return module_path, tool_results


async def main():
    """Main entry point."""
    parser = argparse.ArgumentParser(
        description="Run quality checks on Python modules",
        formatter_class=argparse.RawDescriptionHelpFormatter,
        epilog="Accepts files or directories. Determines module roots automatically.",
    )
    parser.add_argument(
        "paths",
        nargs="+",
        type=Path,
        help="Files or directories to check",
    )
    parser.add_argument(
        "-o",
        "--output-dir",
        type=Path,
        help="Directory to write JSON output file (in addition to stdout)",
    )
    parser.add_argument(
        "--blind",
        action="store_true",
        help="Blind mode: aggregate errors by tool and error type only, without file paths",
    )

    args = parser.parse_args()

    # Generate config files from pyproject.toml excludes
    excludes = extract_excludes_from_pyproject()
    generate_ast_grep_config(excludes)
    semgrepignore_path = generate_semgrep_ignore(excludes)

    # Find unique module roots
    module_roots = find_unique_module_roots(args.paths)

    if not module_roots:
        print("Error: No valid module roots found", file=sys.stderr)
        sys.exit(1)

    print(f"Found {len(module_roots)} unique module(s) to check", file=sys.stderr)

    # Run checks in parallel for all modules
    results = await asyncio.gather(
        *[run_checks_for_module(root) for root in sorted(module_roots)],
        return_exceptions=True
    )

    # Aggregate results from all modules
    all_tool_results = []
    for result in results:
        if isinstance(result, Exception):
            print(f"Module check failed: {result}", file=sys.stderr)
            continue
        _, tool_results = result
        all_tool_results.extend(tool_results)

    # Run pyright once on project-wide (not per-module)
    # Pyright must run without explicit paths to respect exclude patterns
    print("Running pyright on project", file=sys.stderr)
    try:
        pyright_result = await run_pyright(Path("."))  # Path ignored, just for signature
        all_tool_results.append(pyright_result)
    except Exception as e:
        print(f"Pyright execution failed: {e}", file=sys.stderr)

    # Run pyrefly once on project-wide (not per-module)
    # Pyrefly must run without explicit paths to respect exclude patterns
    print("Running pyrefly on project", file=sys.stderr)
    try:
        pyrefly_result = await run_pyrefly(Path("."))  # Path ignored, just for signature
        all_tool_results.append(pyrefly_result)
    except Exception as e:
        print(f"Pyrefly execution failed: {e}", file=sys.stderr)

    # Run mypy once on project-wide (not per-module)
    # Mypy must run without explicit paths to respect exclude patterns
    print("Running mypy on project", file=sys.stderr)
    try:
        mypy_result = await run_mypy(Path("."))  # Path ignored, just for signature
        all_tool_results.append(mypy_result)
    except Exception as e:
        print(f"Mypy execution failed: {e}", file=sys.stderr)

    # Run import-linter once on project-wide (not per-module)
    print("Running import-linter on project", file=sys.stderr)
    try:
        importlinter_result = await run_importlinter()
        all_tool_results.append(importlinter_result)
    except Exception as e:
        print(f"Import-linter execution failed: {e}", file=sys.stderr)

    # Aggregate errors across all modules
    report = aggregate_errors(all_tool_results)

    # Convert to JSON (blind mode or full mode)
    if args.blind:
        output = report_to_dict_blind(report)
    else:
        output = report_to_dict(report)

    json_output = json.dumps(output, indent=2)

    # Output to stdout
    print(json_output)

    # Optionally write to output directory
    if args.output_dir:
        args.output_dir.mkdir(parents=True, exist_ok=True)
        output_file = args.output_dir / "quality-check-results.json"
        output_file.write_text(json_output)
        print(f"Results written to: {output_file}", file=sys.stderr)

    # Cleanup generated files
    try:
        if semgrepignore_path.exists():
            semgrepignore_path.unlink()
            print(f"Cleaned up {semgrepignore_path}", file=sys.stderr)
    except Exception as e:
        print(f"Warning: Failed to cleanup {semgrepignore_path}: {e}", file=sys.stderr)

    # Exit with non-zero if any errors found
    sys.exit(0 if report.verdict == "PASS" else 1)


if __name__ == "__main__":
    asyncio.run(main())
