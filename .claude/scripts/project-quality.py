def parse_mypy_output(output: str) -> list[Error]:
    """Parse mypy output into Error objects."""
    errors = []
    # Mypy text format: file.py:line:column: severity: message [error-code]
    # Example: src/foo.py:10:5: error: Incompatible return type [return-value]
    pattern = r"^(.+?):(\d+):(\d+):\s*(error|warning|note):\s*(.+?)(?:\s*\[([^\]]+)\])?$"
    for line in output.splitlines():
        match = re.match(pattern, line.strip())
        if match:
            file_path, line_no, _, severity, message, code = match.groups()
            # Skip notes, only report errors and warnings
            if severity in ("error", "warning"):
                errors.append(
                    Error(
                        file=file_path,
                        line=int(line_no),
                        code=code or "unknown",
                        message=message.strip(),
                        tool="mypy",
                        severity=severity,
                    )
                )
    return errors


def parse_ruff_output(output: str) -> list[Error]:
    """Parse ruff JSON output into Error objects."""
    errors = []
    try:
        data = json.loads(output)
        # Ruff JSON is an array of violation objects
        if isinstance(data, list):
            for item in data:
                errors.append(
                    Error(
                        file=item.get("filename", ""),
                        line=item.get("location", {}).get("row", 0),
                        code=item.get("code", "unknown"),
                        message=item.get("message", ""),
                        tool="ruff",
                    )
                )
    except (json.JSONDecodeError, KeyError, TypeError):
        # Fallback to text parsing if JSON parsing fails
        pattern = r"^(.+?):(\d+):(\d+):\s*([A-Z]\d+)\s+(.+)$"
        for line in output.splitlines():
            match = re.match(pattern, line.strip())
            if match:
                file_path, line_no, _, code, message = match.groups()
                errors.append(
                    Error(
                        file=file_path,
                        line=int(line_no),
                        code=code,
                        message=message.strip(),
                        tool="ruff",
                    )
                )
    return errors


def parse_ast_grep_output(output: str) -> list[Error]:
    """Parse ast-grep output into Error objects."""
    errors = []
    # ast-grep outputs JSON array with structure:
    # [{"ruleId": "...", "severity": "...", "file": "...", "message": "...", "range": {...}, ...}]
    try:
        data = json.loads(output)
        if isinstance(data, list):
            for item in data:
                errors.append(
                    Error(
                        file=item.get("file", ""),
                        line=item.get("range", {}).get("start", {}).get("line", 0),
                        code=item.get("ruleId", "ast-grep"),
                        message=item.get("message", ""),
                        tool="ast-grep",
                        severity=item.get("severity", "error"),
                    )
                )
    except (json.JSONDecodeError, KeyError, TypeError):
        # Fallback to text parsing
        for line in output.splitlines():
            if ":" in line:
                parts = line.split(":", 3)
                if len(parts) >= 3:
                    errors.append(
                        Error(
                            file=parts[0],
                            line=int(parts[1]) if parts[1].isdigit() else None,
                            code="ast-grep",
                            message=parts[2] if len(parts) > 2 else line,
                            tool="ast-grep",
                        )
                    )
    return errors


def parse_semgrep_output(output: str) -> list[Error]:
    """Parse semgrep output into Error objects."""
    errors = []
    try:
        data = json.loads(output)
        results = data.get("results", [])
        for result in results:
            errors.append(
                Error(
                    file=result.get("path", ""),
                    line=result.get("start", {}).get("line"),
                    code=result["check_id"],
                    message=result.get("extra", {}).get("message", ""),
                    tool="semgrep",
                    severity=result.get("extra", {}).get("severity", "error"),
                )
            )
    except (json.JSONDecodeError, KeyError):
        # Fallback to text parsing if JSON fails
        pass
    return errors


def parse_importlinter_output(output: str) -> list[Error]:
    """Parse import-linter output into Error objects."""
    errors = []
    # import-linter shows contract violations
    # Format varies, look for common patterns
    current_contract = ""
    for line in output.splitlines():
        if "Contract" in line and "BROKEN" in line:
            current_contract = line.strip()
        elif "->" in line and current_contract:
            # This is likely a violation
            errors.append(
                Error(
                    file="",  # import-linter doesn't give file:line
                    line=None,
                    code="import-linter",
                    message=f"{current_contract}: {line.strip()}",
                    tool="import-linter",
                )
            )
    return errors


async def run_pyright(module_path: Path) -> ToolResult:
    """Run pyright on module.

    Note: pyright must be run without explicit paths to respect exclude patterns.
    When explicit paths are passed, excludes are ignored. We run it once for the
    whole project using pyproject.toml configuration.
    """
    # Run pyright with NO path arguments - uses include/exclude from pyproject.toml
    # Passing explicit paths overrides exclude configuration
    cmd = ["uv", "run", "pyright", "--outputjson"]

    stdout, stderr, exit_code = await run_command(cmd)

    errors = parse_pyright_output(stdout) + parse_pyright_output(stderr)

    return ToolResult(
        tool="pyright",
        success=exit_code == 0,
        errors=errors,
        stdout=stdout,
        stderr=stderr,
        exit_code=exit_code,
    )


